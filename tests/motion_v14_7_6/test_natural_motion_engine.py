"""tests/motion_v14_7_6/test_natural_motion_engine.py — Phase B Natural Motion Engine & IK Metrics Tests.

Executes `packs/squire/motion_engine.js` directly in Node ESM against `MotionPlan` tracks
generated by `tools/motion_performance.py` and verifies:
1. Quantified before/after foot-drift reduction (`legacy > 0.03` vs `natural <= 0.03`).
2. `peak_hand_grip_dist_norm <= 0.04` across physical `CONTACT` / `EXERT` intervals.
3. `max_adjacent_joint_jump_norm <= 0.25` at 24 fps across phase boundaries.
4. Multi-actor shared object coupling (`evaluateMultiActorInteraction`) on heavy amphora lift.
5. Frame-order-independent pure determinism (serial == reversed == shuffled SHA-256).
6. Negative fixtures for broken hand contact and sliding stance foot.
"""

from __future__ import annotations

import hashlib
import json
import subprocess
from pathlib import Path
from typing import Any, Dict, List

from tools.action_capabilities import get_pack_capabilities
from tools.motion_performance import (
    build_shared_motion_timeline,
    extract_semantic_motion_intents,
    plan_actor_motion_phases,
)

ROOT_DIR = Path(__file__).resolve().parent.parent.parent
MOTION_ENGINE_REL = "./packs/squire/motion_engine.js"


def run_node_motion_eval(payload: Dict[str, Any]) -> Dict[str, Any]:
    js_code = f"""
import * as ME from '{MOTION_ENGINE_REL}';
import fs from 'node:fs';

const input = JSON.parse(fs.readFileSync(0, 'utf8'));
const mode = input.mode;

if (mode === 'trace_plan') {{
  const tracks = input.plan.tracks;
  const wsMap = Object.fromEntries((input.plan.world_states || []).map((w) => [w.shot_id, w]));
  const reports = tracks.map((tr) => {{
    const sameShotTracks = tracks.filter((x) => x.shot_id === tr.shot_id);
    return ME.validateMotionFrameTrace(tr, wsMap[tr.shot_id] || {{}}, {{
      fps: 24,
      seed: input.plan.seed || 1476,
      allTracks: sameShotTracks,
    }});
  }});
  const legacyWalk = ME.measureLegacySineGaitDrift({{
    fromX: 0.26,
    toX: 0.56,
    groundY: 0.84,
    heightNorm: 0.28,
    dur: 2.4,
    fps: 24,
  }});
  process.stdout.write(JSON.stringify({{ reports, legacyWalk }}));
}} else if (mode === 'determinism_order') {{
  const tr = input.track;
  const ws = input.worldState || {{}};
  const times = input.times;
  const out = times.map((t) => ({{
    t,
    eval: ME.evaluateMotionTrackAt(tr, t, ws, {{ seed: 1476 }}),
  }}));
  out.sort((a, b) => a.t - b.t);
  process.stdout.write(JSON.stringify({{ frames: out }}));
}}
"""
    proc = subprocess.run(
        ["node", "--input-type=module", "-e", js_code],
        cwd=ROOT_DIR,
        input=json.dumps(payload),
        capture_output=True,
        text=True,
        check=True,
        timeout=30,
    )
    return json.loads(proc.stdout)


def _make_plan(script: str, cast: Dict[str, Any], world: Dict[str, Any]) -> Dict[str, Any]:
    intents = extract_semantic_motion_intents(script, cast_bible=cast, world_state=world, pack="squire", genre="civic")
    caps = get_pack_capabilities("squire", "civic")
    tracks = plan_actor_motion_phases(intents, caps, cast_bible=cast, world_state=world)
    plan = build_shared_motion_timeline(None, tracks, world, intents=intents, pack="squire", genre="civic")
    return plan.model_dump()


def test_before_after_foot_drift_and_three_unseen_scripts_metrics() -> None:
    cases: List[Dict[str, Any]] = [
        _make_plan(
            "A citizen slips on wet stone and steadies a woven basket.",
            {"citizen": {"role": "citizen", "preset": "senator", "x": 0.34, "y": 0.84}},
            {"objects": {"basket": {"kind": "basket", "x": 0.44, "y": 0.76}}},
        ),
        _make_plan(
            "A merchant lifts a heavy amphora together with another person.",
            {
                "merchant": {"role": "merchant", "preset": "senator", "x": 0.43, "y": 0.84},
                "dock_helper": {"role": "helper", "preset": "peasant", "x": 0.57, "y": 0.84},
            },
            {"objects": {"amphora": {"kind": "amphora", "x": 0.50, "y": 0.78}}},
        ),
        _make_plan(
            "A child walks toward a hanging lantern, then ducks from a sudden gust of wind.",
            {"child": {"role": "child", "preset": "peasant", "x": 0.26, "y": 0.84, "height_norm": 0.20}},
            {"objects": {"lantern": {"kind": "lantern", "x": 0.58, "y": 0.68}}},
        ),
    ]

    for idx, plan_dict in enumerate(cases):
        res = run_node_motion_eval({"mode": "trace_plan", "plan": plan_dict})
        legacy_med = res["legacyWalk"]["median_planted_foot_drift_norm"]
        assert legacy_med > 0.03, f"Expected legacy constant-v eased walk to exhibit foot drift > 0.03, got {legacy_med}"

        for rep in res["reports"]:
            assert rep["valid"] is True, f"Case {idx} actor {rep['actorId']} failed trace: {rep['violations']}"
            assert rep["median_planted_foot_drift_norm"] <= 0.03
            if rep["contact_frames_evaluated"] > 0:
                assert rep["peak_hand_grip_dist_norm"] <= 0.04
            assert rep["max_adjacent_joint_jump_norm"] <= 0.25


def test_frame_order_independent_pure_determinism() -> None:
    plan_dict = _make_plan(
        "A child walks toward a hanging lantern, then ducks from a sudden gust of wind.",
        {"child": {"role": "child", "preset": "peasant", "x": 0.26, "y": 0.84, "height_norm": 0.20}},
        {"objects": {"lantern": {"kind": "lantern", "x": 0.58, "y": 0.68}}},
    )
    track = plan_dict["tracks"][0]
    ws = plan_dict["world_states"][0]
    t0, t1 = float(track["start_sec"]), float(track["end_sec"])
    n_frames = int(round((t1 - t0) * 24))
    serial_times = [round(t0 + i / 24.0, 6) for i in range(n_frames)]
    reversed_times = list(reversed(serial_times))
    shuffled_times = serial_times[1::2] + serial_times[0::2]

    r_serial = run_node_motion_eval({"mode": "determinism_order", "track": track, "worldState": ws, "times": serial_times})
    r_rev = run_node_motion_eval({"mode": "determinism_order", "track": track, "worldState": ws, "times": reversed_times})
    r_shuf = run_node_motion_eval({"mode": "determinism_order", "track": track, "worldState": ws, "times": shuffled_times})

    h_serial = hashlib.sha256(json.dumps(r_serial, sort_keys=True).encode()).hexdigest()
    h_rev = hashlib.sha256(json.dumps(r_rev, sort_keys=True).encode()).hexdigest()
    h_shuf = hashlib.sha256(json.dumps(r_shuf, sort_keys=True).encode()).hexdigest()

    assert h_serial == h_rev == h_shuf


def test_negative_fixture_broken_contact_and_foot_skate_rejected() -> None:
    # Negative 1: Contact anchor placed impossibly high above actor (y=0.05) so hand hovers far away (>0.04*h)
    plan_bad_contact = _make_plan(
        "A citizen slips on wet stone and steadies a woven basket.",
        {"citizen": {"role": "citizen", "preset": "senator", "x": 0.34, "y": 0.84}},
        {"objects": {"basket": {"kind": "basket", "x": 0.44, "y": 0.05}}},
    )
    res_bad = run_node_motion_eval({"mode": "trace_plan", "plan": plan_bad_contact})
    rep = res_bad["reports"][0]
    assert rep["valid"] is False
    assert rep["peak_hand_grip_dist_norm"] > 0.04

    # Negative 2: Planted foot forced to drift while marked planted
    plan_skate = _make_plan(
        "A merchant lifts a heavy amphora together with another person.",
        {
            "merchant": {"role": "merchant", "preset": "senator", "x": 0.43, "y": 0.84},
            "dock_helper": {"role": "helper", "preset": "peasant", "x": 0.57, "y": 0.84},
        },
        {"objects": {"amphora": {"kind": "amphora", "x": 0.50, "y": 0.78}}},
    )
    # Inject stationary-flagged phases that actually slide root across screen (>0.03*h median & >0.08*h peak)
    for ph in plan_skate["tracks"][0]["phases"]:
        ph["world_start"] = [0.35, 0.84]
        ph["world_end"] = [0.62, 0.84]
        ph["foot_planted_left"] = True
        ph["foot_planted_right"] = True
    # Also remove upper-body contact clamp so root slide manifests directly on planted feet
    plan_skate["tracks"][0]["contacts"] = []
    res_skate = run_node_motion_eval({"mode": "trace_plan", "plan": plan_skate})
    assert res_skate["reports"][0]["valid"] is False
    assert res_skate["reports"][0]["median_planted_foot_drift_norm"] > 0.03
